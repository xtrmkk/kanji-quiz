# S4 川をのぼる船とすれちがい（速さ）
#   P君は下流A→上流B。予定 T0 分。t1 分こいだところで手を止め、d 分流され、
#   こぎ直して合計 T1 分かかった。e＝T1−d−T0 とすると
#     （静水の速さ）:（流れ）＝(d+e):e、Pの上りの速さ＝d/e（流れを1として）
#   Q君は上流B→下流A。静水の速さはP君の r 倍。
# ══════════════════════════════════════════════════════════════════
def _s4_solve(T0, t1, d, e, r):
    pv = F(d + e, e)                      # 静水の速さ（流れ＝1）
    up = pv - 1                           # P の上りの速さ
    L = up * T0                           # AB間の道のり
    qd = r * pv + 1                       # Q の下りの速さ
    tA = L / (up + qd)                    # 両方がこいでいる間に出会うなら
    if tA <= t1:
        t2, zone = tA, 'A'
    else:                                 # P が流されている間に出会う
        t2 = (L - (up + 1) * t1) / (r * pv)
        zone = 'B' if t1 < t2 <= t1 + d else 'C'
    half = r * pv / 2                     # 速さを半分にしたあとの Q（対地）−1
    s_low = (L - (up + 1) * t1) / half - (t1 + d)
    return pv, up, L, t2, zone, s_low


def s4_variants(limit=120):
    """S4：予定の時間・手を止める時刻・流される時間・Q君の割合を振る。"""
    out = []
    for T0 in (60, 48, 72, 90, 54):
        for e in (3, 4, 5, 6):
            for d in (12, 15, 16, 18, 20, 24):
                if d <= e or (T0 * d) % e:
                    continue
                for t1 in (20, 24, 25, 28, 30, 35, 36):
                    if t1 >= T0:
                        continue
                    for r in (F(4, 5), F(3, 4), F(2, 3), F(3, 5), F(1, 2)):
                        pv, up, L, t2, zone, s_low = _s4_solve(T0, t1, d, e, r)
                        if zone != 'B' or s_low <= 0 or s_low >= t2:
                            continue
                        if (t2 * 60).denominator != 1 or (s_low * 60).denominator != 1:
                            continue
                        if (r * pv).denominator != 1 or (r * pv) % 2:
                            continue          # 「半分にする」がきれいに言える組だけ
                        rc = r * 100
                        if rc.denominator != 1:
                            continue
                        n1, n2 = ratio_of(pv, F(1))
                        out.append({
                            'p': {'T0': T0, 't1': t1, 'd': d, 'T1': T0 + d + e,
                                  'rc': int(rc),
                                  'key': f'{T0}-{t1}-{d}-{e}-{r.numerator}{r.denominator}'},
                            'a': [f'{n1} ： {n2}', f'{_mmss(t2)}後', f'{_mmss(s_low)}後'],
                            '_chk': (pv, up, L, t2, s_low),
                        })
    out.sort(key=lambda v: 0 if v['p']['key'] == '60-25-16-4-45' else 1)
    return out[:limit]


