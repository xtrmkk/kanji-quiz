def _mmss(t: F) -> str:
    """分（分数）を「○分○秒」にする。割り切れないものは呼ぶ側ではじく。"""
    m = int(t)
    s = (t - m) * 60
    assert s.denominator == 1, t
    return f'{m}分{int(s)}秒' if s else f'{m}分'


def _divisors(n):
    d, i = [], 1
    while i * i <= n:
        if n % i == 0:
            d.append(i)
            if i != n // i:
                d.append(n // i)
        i += 1
    return sorted(d)


