# S1 くだものの個数と売り上げ（割合と比）
#   (1) 個数の比と売り上げの合計 → 売れた個数の合計
#   (2) 売り上げの比と個数の合計 → 売り上げの合計
# ══════════════════════════════════════════════════════════════════
def s1_variants(limit=120):
    """S1：単価・個数の比・売り上げの比を振る。"""
    out = []
    for a, b in ((150, 400), (120, 300), (200, 500), (180, 450),
                 (150, 250), (250, 400), (160, 240)):
        for p, q in ((4, 3), (3, 2), (5, 3), (3, 4), (5, 4), (2, 3)):
            for k in (6, 8, 9, 10, 12):
                T1 = k * (a * p + b * q)
                if not 6000 <= T1 <= 30000 or T1 % 100:
                    continue
                for r, s in ((2, 3), (3, 4), (1, 2), (3, 2), (4, 3)):
                    g = gcd(r * b, s * a)
                    x0, y0 = r * b // g, s * a // g
                    for m in (1, 2, 3, 4, 5):
                        N = m * (x0 + y0)
                        if not 30 <= N <= 90:
                            continue
                        x, y = m * x0, m * y0
                        T2 = a * x + b * y
                        if T2 % 100:
                            continue
                        out.append({
                            'p': {'a': a, 'b': b, 'p': p, 'q': q, 'T1': T1,
                                  'r': r, 's': s, 'N': N,
                                  'key': f'{a}-{b}-{p}{q}-{k}-{r}{s}-{m}'},
                            'a': [f'{k * (p + q)} 個', f'{T2} 円'],
                            '_chk': (k, x, y, T2),
                        })
    out.sort(key=lambda v: 0 if v['p']['key'] == '150-400-43-8-23-2' else 1)
    return out[:limit]


