# ══════════════════════════════════════════════════════════════════
# S6 / S6a カードを裏返す3つの操作（場合の数）
#   〈操作1〉1回目の目が偶数なら偶数のカード、奇数なら奇数のカードを裏返す
#   〈操作2〉2回目の目のすべての倍数のカードを裏返す
#   〈操作3〉3回目の目のすべての約数のカードを裏返す
# ══════════════════════════════════════════════════════════════════
def op1(a, m=6):
    return frozenset(x for x in range(1, m + 1) if x % 2 == a % 2)


def op2(b, m=6):
    return frozenset(x for x in range(1, m + 1) if x % b == 0)


def op3(c, m=6):
    return frozenset(x for x in range(1, m + 1) if c % x == 0)


def _back(a, b, c, m=6):
    """3つの操作のあとで裏が上になっているカードの集合。"""
    return op1(a, m) ^ op2(b, m) ^ op3(c, m)


def _nums(st):
    return '、'.join(str(x) for x in sorted(st))


_EXAMPLES = ((4, 3, 2), (2, 4, 3), (5, 2, 6), (3, 6, 4), (6, 2, 5), (1, 5, 4))


def s6_variants(limit=120):
    """S6：(1) 目を決めて裏を答える／(2) 2回目の目をあてる。"""
    out = []
    m = 6
    for ex in _EXAMPLES:
        for a1, b1, c1 in ((3, 3, 4), (2, 2, 6), (5, 4, 3), (4, 6, 5),
                           (1, 2, 4), (6, 3, 6), (3, 5, 2), (2, 6, 3)):
            bk1 = _back(a1, b1, c1, m)
            if not 2 <= len(bk1) <= 5:
                continue
            for a2, c2 in ((2, 6), (3, 4), (5, 6), (4, 3), (1, 5), (6, 2)):
                for b2 in range(1, 7):
                    bk2 = _back(a2, b2, c2, m)
                    if not 1 <= len(bk2) <= 3:
                        continue
                    if len([b for b in range(1, 7)
                            if _back(a2, b, c2, m) == bk2]) != 1:
                        continue
                    out.append({
                        'p': {'ea': ex[0], 'eb': ex[1], 'ec': ex[2],
                              'a1': a1, 'b1': b1, 'c1': c1,
                              'a2': a2, 'c2': c2, 'bk2': _nums(bk2),
                              'key': f'{ex[0]}{ex[1]}{ex[2]}-{a1}{b1}{c1}-'
                                     f'{a2}{b2}{c2}'},
                        'a': [_nums(bk1), str(b2)],
                        '_chk': (bk1, bk2, b2),
                    })
    out.sort(key=lambda v: 0 if v['p']['key'] == '432-334-246' else 1)
    return out[:limit]


def s6a_variants(limit=120):
    """S6a：(3) 2回目と3回目の目をあてる／(4) 目の出方を数える。"""
    out = []
    m = 6
    full = frozenset(range(1, m + 1))
    for ex in _EXAMPLES:
        for a3 in (1, 2, 3, 4, 5, 6):
            for b3, c3 in itertools.product(range(1, 7), repeat=2):
                bk3 = _back(a3, b3, c3, m)
                if not 2 <= len(bk3) <= 4:
                    continue
                if len([(b, c) for b in range(1, 7) for c in range(1, 7)
                        if _back(a3, b, c, m) == bk3]) != 1:
                    continue
                for fr4 in ((2, 3, 5), (1, 4, 6), (1, 2, 3), (3, 4, 5),
                            (2, 5, 6), (1, 3, 6)):
                    back4 = full - frozenset(fr4)
                    cnt = sum(1 for a in range(1, 7) for b in range(1, 7)
                              for c in range(1, 7)
                              if _back(a, b, c, m) == back4)
                    if not 4 <= cnt <= 30:
                        continue
                    out.append({
                        'p': {'ea': ex[0], 'eb': ex[1], 'ec': ex[2],
                              'a3': a3, 'bk3': _nums(bk3), 'fr4': _nums(fr4),
                              'key': f'{ex[0]}{ex[1]}{ex[2]}-{a3}{b3}{c3}-'
                                     f'{"".join(map(str, fr4))}'},
                        'a': [str(b3), str(c3), f'{cnt} 通り'],
                        '_chk': (bk3, b3, c3, back4, cnt),
                    })
    out.sort(key=lambda v: 0 if v['p']['key'] == '432-145-235' else 1)
    return out[:limit]


