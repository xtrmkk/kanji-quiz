# S3 立方体の切り口（立体図形）
#   上面 z=a を A(0,a,a) B(0,0,a) C(a,0,a) D(a,a,a)、下面 z=0 を
#   E(0,a,0) F(0,0,0) G(a,0,0) H(a,a,0) と置くと、u＝x+y−z で切り口が決まる。
#   A・C・F の平面は u=0（正三角形 S）。AD・DC・FG を n 等分した k 番目の
#   3点を通る平面は u＝ka/n で、面積は S の (n²+2kn−2k²)/n² 倍。
# ══════════════════════════════════════════════════════════════════
def _s3_ratio(n, k):
    return F(n * n + 2 * k * n - 2 * k * k, n * n)


def s3_variants(limit=120):
    """S3：1辺の長さ・等分の数・2つの平面の位置を振る。"""
    out = []
    for n in (4, 6):
        for a in (4, 6, 8, 12, 16, 18):
            if a % n:
                continue
            for k1, k2 in itertools.combinations(range(1, n), 2):
                # k1<k2 にしておくと、図の上辺が A—I—L—D の順に並ぶ（原本と同じ）。
                # (1) のほうが答えがやさしくなる組だけを採る。
                r1, r2 = _s3_ratio(n, k1), _s3_ratio(n, k2)
                if r1.denominator > r2.denominator or r2.denominator > 18:
                    continue
                out.append({
                    'p': {'a': a, 'n': n, 'k1': k1, 'k2': k2,
                          'key': f'{a}-{n}-{k1}-{k2}'},
                    'a': [f'{frac_html(r1)} 倍', f'{frac_html(r2)} 倍'],
                    '_chk': (r1, r2),
                })
    out.sort(key=lambda v: 0 if v['p']['key'] == '4-4-2-3' else 1)
    return out[:limit]


