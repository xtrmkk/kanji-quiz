# S2 積が決まっている2つの整数（公約数）
#   積 M＝p²m（m は平方の因数をもたず p と互いに素）のとき、
#   「1以外の公約数をもつ」⇔ A も B も p の倍数。A＝pa, B＝pb, ab＝m。
# ══════════════════════════════════════════════════════════════════
def s2_variants(limit=120):
    """S2：くり返す素数 p と、残りの積 m を振る。"""
    out = []
    primes = (2, 3, 5, 7, 11, 13, 17, 19, 23)
    ms = []                                   # 相異なる素数の積（平方の因数なし）
    for r in (3, 4):
        for ps in itertools.combinations(primes, r):
            m = 1
            for x in ps:
                m *= x
            if 300 <= m <= 2000:
                ms.append(m)
    ms.sort()
    for p in (2, 3, 5, 7):
        for m in ms:
            if m % p == 0 or m > 2000:
                continue
            M = p * p * m
            if not 2000 <= M <= 60000:
                continue
            cand = [p * d for d in _divisors(m) if d * d < m]
            two = [A for A in cand if 10 <= A <= 99]
            if not 4 <= len(two) <= 7:
                continue
            out.append({
                'p': {'M': M, 'key': f'{p}-{m}'},
                'a': ['、'.join(str(A) for A in two)],
                '_chk': (p, m, cand, two),
            })
    out.sort(key=lambda v: 0 if v['p']['key'] == '3-770' else 1)
    return out[:limit]


