def _show(name, subs):
    import collections
    print(f'【{name}】設問 {len(subs)} 問 ／ 配点合計 {sum(s[4] for s in subs)} 点')
    g = collections.OrderedDict()
    for q, sub, nm, rate, score, mark in subs:
        g.setdefault(q, []).append((sub, nm, rate, score, mark))
    for q, ss in g.items():
        print(f'  大問{q}: ' + '／'.join(f'{s[0] or "—"} {s[2]}%' for s in ss))
    c = collections.Counter(s[5] for s in subs)
    print('  正誤:', dict(c),
          '／ ○の配点合計', sum(s[4] for s in subs if s[5] == '○'), '点',
          '／ △', sum(s[4] for s in subs if s[5] == '△'), '点')


